import { sanitizePhone } from "../global-utils";

export const mapEmployeeToBackend = (formData) => ({
  id: formData.id ? formData.id : Date.now(),
  ci: formData.ci,
  num_employee: formData.numEmployee,
  first_name: formData.firstName,
  second_name: formData.secondName,
  last_name: formData.lastName,
  second_last_name: formData.secondLastName,
  birthdate: formData.birthdate,
  place_of_birth: formData.placeOfBirth,
  nationality: formData.nationality,
  sex: formData.sex,
  marital_status: formData.maritalStatus,
  blood_type: formData.bloodType ?? '',
  email: formData.email,
  mobile_phone: formData.mobilePhone ? sanitizePhone(`${formData.mobilePhoneCode}-${formData.mobilePhone}`) : null,
  home_phone: formData?.homePhone ? `${formData.homePhoneCode}${formData.homePhone}` : null,
  address: formData.address,
  city_address: formData.cityAddress,
  hire_date: formData.joinDate,
  department_id: formData.department,
  subdepartment_id: formData.subDepartment,
  position_id: formData.position,
  username: formData.userName,
  password: formData.userPass,
  change_pass_next_login: formData.changePassNextLogin,
  status: formData.status,
  use_meru_link: formData.useMeruLink,
  ...(formData.useMeruLink ? { role_id: formData.roleId || null } : {}),  //formData.roleId || null,
  permissions: formData.permissions || [],
  departments: formData.departmentCollectedIds || [],
  use_hid_card: formData.useHidCard,
  use_locker: formData.useLocker,
  use_transport: formData.useTransport,
  contacts: formData.contacts?.map(contact => ({
    name: contact.name,
    last_name: contact.lastName,
    relationship: contact.relationship,
    phone: contact.phone ? sanitizePhone(`${contact.phoneCode}${contact.phone}`) : null,
    address: contact.address,
  })),
  bank_information: formData.bankInformation?.map(bank => ({
    bank_name: bank.bankName,
    account_number: bank.accountNumber,
    mobile_pay_number: bank.mobilePayNumber
      ? sanitizePhone(`${bank.mobilePayCode}${bank.mobilePayNumber}`)
      : null,
  })),
  assign_id: formData?.lockerAssingId ?? null
});